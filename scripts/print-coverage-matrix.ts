#!/usr/bin/env tsx
/**
 * Generates NULLLAB's vulnerability coverage matrix from the actual state
 * of the repository — never hand-asserted. A subcategory only shows as
 * "implemented" because a real lab manifest exists for it, and only shows
 * as tested/verified/documented because docs/lab-verification-status.json
 * says so for that specific lab id. Nothing here is aspirational.
 *
 * Usage: npm run coverage:matrix
 * Writes docs/coverage-matrix.md and prints a summary to the console.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FAMILIES, LabManifestSchema, type FamilyId } from "../packages/shared/src/index.js";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LABS_ROOT = path.join(REPO_ROOT, "labs");
const STATUS_FILE = path.join(REPO_ROOT, "docs", "lab-verification-status.json");
const OUT_FILE = path.join(REPO_ROOT, "docs", "coverage-matrix.md");

interface VerificationStatus {
  testsPassing?: boolean;
  verifiedBuiltIn?: boolean;
  verifiedExternalClient?: boolean;
  verifiedViaProxy?: boolean;
  documented?: boolean;
  testFile?: string;
  note?: string;
}

function findManifests(root: string): { id: string; family: FamilyId; subcategory: string; title: string }[] {
  const out: { id: string; family: FamilyId; subcategory: string; title: string }[] = [];
  const stack = [root];
  while (stack.length) {
    const dir = stack.pop()!;
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) stack.push(full);
      else if (entry.name === "manifest.json") {
        const parsed = LabManifestSchema.safeParse(JSON.parse(fs.readFileSync(full, "utf8")));
        if (parsed.success) {
          out.push({
            id: parsed.data.id,
            family: parsed.data.family as FamilyId,
            subcategory: parsed.data.subcategory,
            title: parsed.data.title,
          });
        } else {
          console.warn(`[coverage-matrix] skipping invalid manifest at ${full}`);
        }
      }
    }
  }
  return out;
}

function check(v: boolean | undefined): string {
  return v ? "✅" : "⬜";
}

function main() {
  const manifests = findManifests(LABS_ROOT);
  const status: Record<string, VerificationStatus> = fs.existsSync(STATUS_FILE)
    ? JSON.parse(fs.readFileSync(STATUS_FILE, "utf8"))
    : {};

  const byKey = new Map<string, typeof manifests>();
  for (const m of manifests) {
    const key = `${m.family}::${m.subcategory}`;
    const list = byKey.get(key) ?? [];
    list.push(m);
    byKey.set(key, list);
  }

  const lines: string[] = [];
  lines.push("# NULLLAB Vulnerability Coverage Matrix");
  lines.push("");
  lines.push(`Generated by \`npm run coverage:matrix\`. ${manifests.length} lab(s) implemented across ${new Set(manifests.map((m) => m.family)).size} of ${Object.keys(FAMILIES).length} vulnerability families.`);
  lines.push("");
  lines.push("A subcategory is marked **Implemented** only because a real lab manifest exists for it on disk.");
  lines.push("The test/verification columns reflect `docs/lab-verification-status.json` — hand-maintained, except the proxy flag");
  lines.push("(see below), which is generated from a real run. Nothing here is asserted without a corresponding entry.");
  lines.push("");
  lines.push("**\"Verified (raw HTTP client)\"** means the lab's exploit was driven end-to-end by an automated HTTP client");
  lines.push("(plain requests with a cookie jar) against the real spawned target.");
  lines.push("");
  lines.push("**\"Verified via local proxy harness\"** means the same exploit test was re-run with every learner-side request");
  lines.push("routed through a local intercepting-style forward proxy (`npm run test:proxy`, see `tests/integration/proxy.ts`) and the");
  lines.push("control plane's server-side verifier still recorded the solve, within a single test file. This flag is generated from");
  lines.push("that run (`npm run proxy:status`), not typed by hand. It is **not** a Burp Suite result: the harness is a generic");
  lines.push("HTTP/1.1 forward proxy that mimics Burp's plain-HTTP listener. No lab has been tested in Burp itself, and the");
  lines.push("labs triggered in a real browser (XSS, clickjacking, prototype-pollution admin bot) are deliberately not counted,");
  lines.push("because that browser is not routed through the harness.");
  lines.push("");

  let totalSub = 0;
  let implementedSub = 0;

  for (const family of Object.values(FAMILIES)) {
    lines.push(`## ${family.shortCode}. ${family.title}`);
    lines.push("");
    lines.push(family.description);
    lines.push("");
    lines.push("| Subcategory | Planned | Implemented | Lab(s) | Tests passing | Verified (built-in) | Verified (raw HTTP client) | Verified via local proxy harness | Documented |");
    lines.push("|---|:---:|:---:|---|:---:|:---:|:---:|:---:|:---:|");

    for (const sub of family.subcategories) {
      totalSub++;
      const key = `${family.id}::${sub}`;
      const labs = byKey.get(key) ?? [];
      const implemented = labs.length > 0;
      if (implemented) implementedSub++;

      const agg = (field: keyof VerificationStatus) => labs.length > 0 && labs.every((l) => !!status[l.id]?.[field]);

      const labLinks = labs.map((l) => `\`${l.id}\``).join(", ") || "—";
      lines.push(
        `| ${sub} | ✅ | ${check(implemented)} | ${labLinks} | ${check(agg("testsPassing"))} | ${check(agg("verifiedBuiltIn"))} | ${check(agg("verifiedExternalClient"))} | ${check(agg("verifiedViaProxy"))} | ${check(agg("documented"))} |`,
      );
    }
    lines.push("");
  }

  lines.push("---");
  lines.push("");
  lines.push(`**Summary:** ${implementedSub} / ${totalSub} taxonomy subcategories have at least one implemented, tested lab.`);
  lines.push("");
  lines.push(
    "Subcategories without a lab are intentionally left unimplemented rather than stubbed, per the project's own " +
      "\"never claim a category is complete without evidence\" rule. Per-lab weakness mapping: docs/lab-catalogue.md.",
  );

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, lines.join("\n") + "\n", "utf8");

  console.log(lines.join("\n"));
  console.log(`\nWritten to ${path.relative(REPO_ROOT, OUT_FILE)}`);
}

main();
