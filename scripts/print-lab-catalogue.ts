#!/usr/bin/env tsx
/**
 * Generates docs/lab-catalogue.md — the maintainer-facing mapping from every
 * lab to the ONE weakness it teaches, where that weakness lives, and what data
 * is seeded. Generated from the manifests so it can't drift.
 *
 * Usage: npm run docs:labs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FAMILIES, LabManifestSchema, type FamilyId, type LabManifest } from "../packages/shared/src/index.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "docs", "lab-catalogue.md");

function loadAll(): LabManifest[] {
  const out: LabManifest[] = [];
  for (const fam of fs.readdirSync(path.join(ROOT, "labs"), { withFileTypes: true })) {
    if (!fam.isDirectory()) continue;
    for (const lab of fs.readdirSync(path.join(ROOT, "labs", fam.name), { withFileTypes: true })) {
      const file = path.join(ROOT, "labs", fam.name, lab.name, "manifest.json");
      if (lab.isDirectory() && fs.existsSync(file)) out.push(LabManifestSchema.parse(JSON.parse(fs.readFileSync(file, "utf8"))));
    }
  }
  return out;
}

const ORDER = ["beginner", "easy", "medium", "hard", "advanced"];
const labs = loadAll().sort((a, b) => ORDER.indexOf(a.difficulty) - ORDER.indexOf(b.difficulty) || a.id.localeCompare(b.id));
const esc = (s: string) => s.replaceAll("|", "\\|");

const lines: string[] = [
  "# Lab catalogue — weakness map (maintainers)",
  "",
  "> **Spoiler warning.** This file documents where each lab's flaw lives and how it is verified. It is for",
  "> people building and reviewing NULLLAB, not for learners attempting the labs. Generated by `npm run docs:labs`.",
  "",
  `${labs.length} labs. Each teaches exactly one weakness; the contract test fails if two labs claim the same one.`,
  "",
];
for (const family of Object.values(FAMILIES)) {
  const mine = labs.filter((l) => l.family === (family.id as FamilyId));
  if (mine.length === 0) continue;
  lines.push(`## ${family.shortCode}. ${family.title}`, "", "| Lab | Difficulty | Subcategory | The one weakness | Where | Seeded data |", "|---|---|---|---|---|---|");
  for (const l of mine) {
    lines.push(`| \`${l.id}\` | ${l.difficulty} | ${l.subcategory} | ${esc(l.weakness ?? "")} | \`${esc(l.vulnerableEndpoint ?? "")}\` | ${esc(l.seededData ?? "")} |`);
  }
  lines.push("");
}
fs.writeFileSync(OUT, lines.join("\n") + "\n", "utf8");
console.log(`Wrote ${path.relative(ROOT, OUT)} (${labs.length} labs)`);
